module I = struct
  type 'a t =
    { ui_in : 'a [@bits 8]
    ; uio_in : 'a [@bits 8]
    ; ena : 'a
    ; clk : 'a
    ; rst_n : 'a
    }
  [@@deriving hardcaml]
end

module O = struct
  type 'a t =
    { uo_out : 'a [@bits 8]
    ; uio_out : 'a [@bits 8]
    ; uio_oe : 'a [@bits 8]
    }
  [@@deriving hardcaml]
end

module Design = struct
  module I = I
  module O = O

  let name = "tt_um_leemperor_hardcaml_protemu"

  let create context (i : _ I.t) =
    let open Signal in
    (* Match the legacy wrapper: asynchronous assertion, two clock edges of
       synchronous release, and immediate pad gating on reset or disable. *)
    let reset_sync =
      reg_fb
        (Reg_spec.create ~clock:i.clk ~reset:((~:) i.rst_n) ())
        ~reset_to:(Bits.of_int_trunc ~width:2 3)
        ~width:2
        ~f:(fun previous -> concat_msb [ bit previous ~pos:0; zero 1 ])
    in
    let core_reset = bit reset_sync ~pos:1 in
    let core =
      P0_observable.create
        (Elaboration_context.scope context)
        { P0_observable.I.clock_i = i.clk
        ; reset_i = core_reset
        ; enable_i = i.ena
        ; command_valid_i = bit i.ui_in ~pos:6
        ; delay_i = select i.ui_in ~high:3 ~low:0
        ; pin_value_i = concat_msb [ zero 7; bit i.ui_in ~pos:4 ]
        ; pin_oe_i = concat_msb [ zero 7; bit i.ui_in ~pos:5 ]
        }
    in
    let pads_enabled = i.rst_n &: i.ena in
    { O.uo_out =
        mux2
          (pads_enabled &: (~:) core_reset)
          (concat_msb
             [ core.rejected_o
             ; core.done_o
             ; core.busy_o
             ; core.ready_o
             ; core.timer_o
             ])
          (zero 8)
    ; uio_out = mux2 pads_enabled core.pins_o (zero 8)
    ; uio_oe = mux2 pads_enabled core.pin_oe_o (zero 8)
    }
  ;;
end

let pinout : Pinout.t =
  let descriptions = function
    | Pinout.Bank.Ui ->
      [ "P0 delay bit 0"; "P0 delay bit 1"; "P0 delay bit 2"; "P0 delay bit 3"
      ; "P0 protocol pin 0 value"; "P0 protocol pin 0 output enable"
      ; "P0 command valid"; "Reserved" ]
    | Uo ->
      [ "Timer bit 0"; "Timer bit 1"; "Timer bit 2"; "Timer bit 3"
      ; "Command ready"; "Timer busy"; "Command done pulse"
      ; "Command rejected pulse" ]
    | Uio -> List.init 8 ~f:(fun bit -> "Protocol pin " ^ Int.to_string bit)
  in
  List.concat_map [ Pinout.Bank.Ui; Uo; Uio ] ~f:(fun bank ->
    List.mapi (descriptions bank) ~f:(fun bit description ->
      { Pinout.bank; bit; description }))
;;

